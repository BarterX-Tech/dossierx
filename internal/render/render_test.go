func TestOrderClaims_OrderIsScopedPerSectionNotGlobal(t *testing.T) {
	claim := func(id, section string, order int) model.Claim {
		return model.Claim{ID: id, Section: section, Order: order}
	}
	// Two sections, each with its own locally-authored "order: 1, order: 2"
	// sequence, interleaved in SourcePath order the way two sibling section
	// subdirectories would load. A global Order sort would put both
	// "order: 1" claims first (one per section), splitting each section's
	// claims apart and making newGroup emit "section A" then "section B"
	// then "section A" again.
	claims := []model.Claim{
		claim("a1", "A", 1),
		claim("a2", "A", 2),
		claim("b1", "B", 1),
		claim("b2", "B", 2),
	}

	got := orderClaims(claims)

	var gotIDs []string
	for _, c := range got {
		gotIDs = append(gotIDs, c.ID)
	}
	want := []string{"a1", "a2", "b1", "b2"}
	if len(gotIDs) != len(want) {
		t.Fatalf("orderClaims IDs = %v, want %v", gotIDs, want)
	}
	for i := range want {
		if gotIDs[i] != want[i] {
			t.Errorf("orderClaims IDs = %v, want %v — sections must stay contiguous", gotIDs, want)
			break
		}
	}
}

