func TestRender_OverrideMissingPartialFallsBack(t *testing.T) {
	dir := t.TempDir()
	// Only override card.html; every other layout must fall back to the
	// embedded default without erroring.
	overridePath := dir + "/card.html"
	writeFile(t, overridePath, `<section class="claim claim-card override-marker" id="{{.ID}}">OVERRIDDEN: {{.ID}}</section>`)

	cfg := &config.Config{Viewer: config.Viewer{TemplateOverrides: dir}}

	cardCat, err := catalog.Build([]model.Claim{claimFor(model.LayoutCard)}, nil)
	if err != nil {
		t.Fatalf("catalog.Build: %v", err)
	}
	out, err := Render(cardCat, cfg)
	if err != nil {
		t.Fatalf("Render (card, overridden): %v", err)
	}
	if !strings.Contains(out, "override-marker") || !strings.Contains(out, "OVERRIDDEN:") {
		t.Errorf("expected overridden card partial to be used:\n%s", out)
	}

	tableCat, err := catalog.Build([]model.Claim{claimFor(model.LayoutTable)}, nil)
	if err != nil {
		t.Fatalf("catalog.Build: %v", err)
	}
	out, err = Render(tableCat, cfg)
	if err != nil {
		t.Fatalf("Render (table, falls back to default): %v", err)
	}
	if strings.Contains(out, "OVERRIDDEN") {
		t.Errorf("table claim should not pick up the card override:\n%s", out)
	}
	if !strings.Contains(out, `class="claim claim-table`) {
		t.Errorf("expected default table partial to be used:\n%s", out)
	}
}

