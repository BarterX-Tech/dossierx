func TestOrderClaims_ExplicitOrderFirstThenSourcePathFallback(t *testing.T) {
	claim := func(id string, order int) model.Claim {
		return model.Claim{ID: id, Order: order}
	}
	// Incoming order is deliberately not sorted, to prove orderClaims does
	// the sorting rather than merely preserving input order.
	claims := []model.Claim{
		claim("no-order-a", 0),
		claim("order-5", 5),
		claim("no-order-b", 0),
		claim("order-2", 2),
	}

	got := orderClaims(claims)

	var gotIDs []string
	for _, c := range got {
		gotIDs = append(gotIDs, c.ID)
	}
	// order-2 and order-5 sort ascending by Order, ahead of every unordered
	// claim; the two unordered claims keep their incoming relative order
	// (no-order-a before no-order-b) as the stable fallback.
	want := []string{"order-2", "order-5", "no-order-a", "no-order-b"}
	if len(gotIDs) != len(want) {
		t.Fatalf("orderClaims IDs = %v, want %v", gotIDs, want)
	}
	for i := range want {
		if gotIDs[i] != want[i] {
			t.Errorf("orderClaims IDs = %v, want %v", gotIDs, want)
			break
		}
	}
}

