// derived_facts_test.go is layer 1's answer to a finding class that regenerates
// every release: PROSE THAT RESTATES A NUMBER THE TREE ALREADY DERIVES.
//
// WHY THIS FILE EXISTS. The v0.5.2 reading gate ran four rounds — 39, 31, 24, 18
// findings — and the curve decayed without converging. Part of the reason is
// that a whole class of finding is manufactured fresh by every release: a
// sentence, a table row or a count typed by hand that duplicates something
// surface.json already extracts mechanically. Two of them failed inside v0.5.2
// alone:
//
//   - The site's "26 -> 19: what was cut, and where it went" table enumerated
//     TWELVE retired commands. The binary retires SIXTEEN. `lock`, `unlock`,
//     `reaudit` and `flag` were missing, and all four were real top-level
//     commands before v0.3.0 folded them under the claim noun — v0.2.0's
//     root.AddCommand registers newLockCmd, newUnlockCmd, newReauditCmd and
//     newFlagCmd. So an agent that learned the old CLI and reaches for one of
//     them gets a correct answer from the binary and no answer from the one
//     page written to catch exactly that reader.
//   - docs/RELEASING.md's "FIVE pins across FOUR files" sentence, which its own
//     surrounding paragraph admits "has now gone stale twice".
//
// A reading agent can catch either one, but only at release time, only if the
// bundle happened to carry both documents, and only by spending a round. A test
// catches both on every push, for free, and cannot forget.
//
// WHAT MAKES THIS SOUND. surface.json is not a document somebody maintains: it
// is regenerated by cmd/dossierx/surface_test.go's TestGenerateSurfaceJSON and
// compared byte for byte against the committed copy, so a surface change that
// was not regenerated is already a red build. That is what makes it usable here
// as the derived side of a comparison — the prose is checked against a fact, not
// against another piece of prose.
//
// C4 AND C5 WERE ADDED WHEN THIS FILE WAS BROUGHT OVER FROM THE RELEASE BRANCH,
// because the original three checks share a conspicuous gap. surface.json's
// `version_pins` already sweeps the tree for every release-version pin — the
// sweep is how three pin sites the hand-list had missed were found at all — and
// then NOTHING COMPARES THE PINS TO THE VERSION BEING RELEASED. The inventory
// made a stale pin visible and stopped one comparison short of making it a red
// build: C2 checks that the pin PARAGRAPH matches the sweep, C3 that the sweep
// the document prints is the sweep the code runs, and no check said "and every
// pin is the release this tree declares". C4 is that comparison. C5 is the same
// idea for README's counted surface claims ("19 commands under 7 nouns"), which
// the site's meta description has already demonstrated the failure mode for —
// it advertised a 20-command CLI for two minor releases because it was "the one
// count on the page that nothing derives".
//
// WHAT THIS CANNOT REACH. Prose that makes a judgement rather than states a
// number. Most of FORMAT.md is judgement, and no check here pretends otherwise.
// A derived check inherits surface.json's blind spots; it does not invent
// coverage.
