// C3 — the sweep the document prints against the sweep the code runs
// ---------------------------------------------------------------------------

// TestTheDocumentedPinSweepIsTheOneTheCodeRuns closes a gap the v0.5.2 gate found
// one commit after lane C shipped: `surfacePinSweep` in cmd/dossierx/surface_test.go
// calls itself "docs/RELEASING.md's own sweep expression, verbatim", and for one
// commit it was not. The constant gained a third URL shape and the command printed
// in the procedure did not, so a maintainer following the written instruction swept
// for two shapes while the inventory knew three — and the three pins the item was
// rewritten to stop losing were invisible to the person doing the sweeping.
//
// This is the same class as C1 and C2, one level up: not prose restating a derived
// number, but prose restating a derived REGEXP. It is checked the same way.
func TestTheDocumentedPinSweepIsTheOneTheCodeRuns(t *testing.T) {
	const sweepConst = "surfacePinSweep = `"

	source := readRepoFile(t, "cmd/dossierx/surface_test.go")
	i := strings.Index(source, sweepConst)
	if i < 0 {
		t.Fatal("cmd/dossierx/surface_test.go no longer declares surfacePinSweep, so the expression the inventory is built from cannot be read and this check has lost one of its two sides")
	}
	rest := source[i+len(sweepConst):]
	j := strings.Index(rest, "`")
	if j < 0 {
		t.Fatal("surfacePinSweep's raw string literal is unterminated")
	}
	code := rest[:j]

	releasing := readRepoFile(t, "docs/RELEASING.md")
	if !strings.Contains(releasing, code) {
		t.Errorf("docs/RELEASING.md does not print the expression the inventory is actually built from.\n"+
			"  the code sweeps: %s\n\n"+
			"The item tells a maintainer to work from the sweep rather than from the list beside it, so a printed command that is narrower than the code's is worse than no command: it produces a short answer that looks like a complete one. Paste the constant into the `git grep` the item prints.", code)
	}
}

// ---------------------------------------------------------------------------
// C4 — every pin against the release the tree itself declares
// ---------------------------------------------------------------------------

// treeDeclaredVersion is the version this tree says it is releasing, read from
// the two places CLAUDE.md names as the declaration the release driver checks
// the tag against: CHANGELOG.md's newest heading and the entry
// site/releases.html marks `data-current="true"`. The two are cross-checked here and disagreement is FATAL
// rather than a pick-one, because a tree that cannot agree with itself about
// its own version gives this test no side to judge the pins against — and that
// disagreement is itself the defect to report, not to paper over by trusting
// either file alone.
func treeDeclaredVersion(t *testing.T) string {
	t.Helper()

	changelog := readRepoFile(t, "CHANGELOG.md")
	headingRe := regexp.MustCompile(`(?m)^## \[(\d+\.\d+\.\d+)\]`)
	m := headingRe.FindStringSubmatch(changelog)
	if m == nil {
		t.Fatal("CHANGELOG.md carries no `## [X.Y.Z]` release heading, so the version this tree declares cannot be read from it")
	}
	fromChangelog := "v" + m[1]

	// The site's ledger marks its current entry rather than positioning it;
	// siteCurrentRelease (tests/site_ledger_test.go) is the one reader of that
	// marker in this package, and every way of failing to read it is fatal
	// there rather than returning a value this comparison could trust.
	fromSite := siteCurrentRelease(t)

	if fromChangelog != fromSite {
		t.Fatalf("CHANGELOG.md's newest heading declares %s and site/releases.html's entry marked current declares %s. "+
			"These are the two declarations the release driver checks the tag against, and while they disagree there is no version to judge the pins by — fix the declaration before trusting any pin comparison", fromChangelog, fromSite)
	}
	return fromChangelog
}

// TestEveryVersionPinCarriesTheVersionThisTreeDeclares is the comparison the
// inventory stopped one step short of. surface.json's version_pins sweeps the
// tree mechanically — the sweep is how three pin sites the hand-list had missed
// were found at all — and records each pin's file, token and version. Then
// nothing read the `version` column back: C2 counts the pins, C3 checks the
// sweep expression, and a tree could still declare v0.5.2 in its CHANGELOG
// while README's `go install` line handed every new user v0.5.1. That is
// precisely the class this file exists for — the version is a number the tree
// already declares twice (the CHANGELOG heading and the site's release ledger),
// restated by hand at every pin site.
//
// The pin set is read from the inventory, never from a file list written here:
// a pin site created next week enters the sweep on its own and is judged here
// on its own, which is the property the hand-list never had.
//
// WHAT THIS CANNOT REACH. It proves the pins agree with the declaration, not
// that the declared version is releasable: whether the tag exists, whether the
// pinned raw URLs resolve, and whether the published artifact matches this tree
// are docs/RELEASING.md's questions, answered by hand against the published
// archive, which no test over the worktree can see.
func TestEveryVersionPinCarriesTheVersionThisTreeDeclares(t *testing.T) {
	_, pins := surfacePinsAndRetired(t)
	declared := treeDeclaredVersion(t)

	for _, p := range pins {
		if p.Version != declared {
			t.Errorf("%s pins %q at %s, and this tree declares %s (CHANGELOG.md's newest heading, site/releases.html's entry marked current).\n\n"+
				"A pin behind the declaration ships the PREVIOUS release to everyone who follows this document: the `go install` "+
				"line installs the old binary, a raw URL fetches the old script, and a copied CI template gates other people's "+
				"merges with the old engine. Move the pin with the release, or — if the declaration itself is the premature side — "+
				"fix CHANGELOG.md and the site together.", p.File, p.Pin, p.Version, declared)
		}
	}
}

// ---------------------------------------------------------------------------
// C5 — README's counted surface claims against the inventory's counts
// ---------------------------------------------------------------------------

// readmeCountedClaimPatterns are the sentence shapes in which README states a
// COUNT of the current surface. Each pattern's captures map, in order, onto
// keys of surface.json's `counts` block.
//
// The command count is matched only in its anchored "N commands under M nouns"
// form, never as a bare "N commands", and the narrowing is deliberate rather
// than cautious: README also says "Twelve commands were removed and four moved
// in v0.3.0", which is a claim about HISTORY, and surface.json inventories only
// the tree as it is — no current count can confirm or deny what v0.3.0 did.
// Historical enumerations have their own derived check where one is possible
// (C1 pins the site's migration table against the retired set, whose stubs the
// binary still ships); a history sentence a current inventory cannot reach is
// this file's stated blind spot, not a case to half-check.
var readmeCountedClaimPatterns = []struct {
	re   *regexp.Regexp
	keys []string
}{
	{regexp.MustCompile(`(?i)\b(\d+|[a-z]+(?:-[a-z]+)?)\s+(?:leaf\s+)?commands\s+under\s+(\d+|[a-z]+(?:-[a-z]+)?)\s+nouns\b`), []string{"commands", "nouns"}},
	{regexp.MustCompile(`(?i)\b(\d+|[a-z]+(?:-[a-z]+)?)\s+error codes\b`), []string{"error_codes"}},
	{regexp.MustCompile(`(?i)\b(\d+|[a-z]+(?:-[a-z]+)?)\s+lint rules\b`), []string{"lint_rules"}},
	{regexp.MustCompile(`(?i)\b(\d+|[a-z]+(?:-[a-z]+)?)\s+HTTP routes\b`), []string{"http_routes"}},
}

// TestREADMECountedClaimsMatchTheSurfaceInventory pins every count README
// states about the current surface to surface.json's `counts`. The counts block
// exists because hand-typed surface counts are the single most reliable staleness
// generator this project has measured: the site's meta description advertised a
// 20-command CLI from v0.3.0 through two minor releases, "the one count on the
// page that nothing derives", and README states the same numbers twice (the
// two-roles table and the CLI-surface heading), so a release that cuts or adds
// a command has two more places to forget.
//
// No expected value is written here — the day someone adds a twentieth command,
// surface.json's regeneration gate moves the count and this test starts
// demanding README say twenty, with nothing in the test itself to update.
func TestREADMECountedClaimsMatchTheSurfaceInventory(t *testing.T) {
	counts := surfaceCountsInventory(t)
	readme := readRepoFile(t, "README.md")

	found := 0
	for _, pattern := range readmeCountedClaimPatterns {
		for _, m := range pattern.re.FindAllStringSubmatch(readme, -1) {
			for i, key := range pattern.keys {
				token := m[i+1]
				n, ok := proseNumber(token)
				if !ok {
					// An article or stray word the alternation let through is
					// not a counted claim; a pattern that can only match
					// numbers never reaches here, but the word branch of the
					// alternation can. Words that are not numbers are not
					// counts, so they are not claims.
					continue
				}
				found++
				want, known := counts[key]
				if !known {
					t.Fatalf("readmeCountedClaimPatterns maps a capture onto counts[%q], which surface.json does not carry; the pattern table is broken, not README", key)
				}
				if n != want {
					t.Errorf("README states %q — %d %s — and surface.json's counts derive %d.\n\n"+
						"The count is derived from the binary and regenerated on every push, so when the two disagree the prose is "+
						"the stale side. The site's meta description already demonstrated this exact failure: it advertised a "+
						"20-command CLI for two minor releases because nothing derived it.\n  matched: %q",
						strings.TrimSpace(m[0]), n, key, want, m[0])
				}
			}
		}
	}

	// Zero matches means the scanner lost its subject, not that README stopped
	// making counted claims — the two-roles table and the CLI-surface heading
	// both state the command and noun counts today, so an empty scan is a
	// broken extraction and must fail rather than pass over zero assertions.
	if found == 0 {
		t.Fatal("no counted surface claims were extracted from README.md; either README genuinely no longer states any count (update this test deliberately) or the sentence shapes moved out from under readmeCountedClaimPatterns — in both cases a silent zero-assertion pass is the wrong answer")
	}
}

